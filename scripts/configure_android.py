#!/usr/bin/env python3
"""
Post-processes the android/ folder generated by `flutter create`:
  * sets the launcher label to «لَوح»
  * if android/key.properties exists, wires release signing into app/build.gradle
Run from the project root.
"""
import re
import sys
from pathlib import Path

ANDROID = Path("android")
MANIFEST = ANDROID / "app" / "src" / "main" / "AndroidManifest.xml"
GRADLE = ANDROID / "app" / "build.gradle"
KEYPROPS = ANDROID / "key.properties"

LABEL = "لَوح"

LOAD_PROPS = """def keystoreProperties = new Properties()
def keystorePropertiesFile = rootProject.file('key.properties')
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(new FileInputStream(keystorePropertiesFile))
}

"""

SIGNING = """    signingConfigs {
        release {
            keyAlias keystoreProperties['keyAlias']
            keyPassword keystoreProperties['keyPassword']
            storeFile keystoreProperties['storeFile'] ? file(keystoreProperties['storeFile']) : null
            storePassword keystoreProperties['storePassword']
        }
    }

"""


def patch_manifest():
    text = MANIFEST.read_text(encoding="utf-8")
    new, n = re.subn(r'android:label="[^"]*"', f'android:label="{LABEL}"', text, count=1)
    if n != 1:
        sys.exit("Could not set android:label in AndroidManifest.xml")
    MANIFEST.write_text(new, encoding="utf-8")
    print("Manifest label set")


def patch_signing():
    if not KEYPROPS.exists():
        print("No key.properties -> release will be debug-signed (fine for testing, NOT for the store)")
        return
    if not GRADLE.exists():
        sys.exit("android/app/build.gradle not found (Kotlin DSL?). Pin Flutter 3.27.x or adapt this script.")
    text = GRADLE.read_text(encoding="utf-8")
    if "keystoreProperties" in text:
        print("Signing already configured")
        return

    m = re.search(r"^android\s*\{", text, flags=re.M)
    if not m:
        sys.exit("Could not find the android { block")
    text = text[: m.start()] + LOAD_PROPS + text[m.start():]

    m = re.search(r"^\s*buildTypes\s*\{", text, flags=re.M)
    if not m:
        sys.exit("Could not find buildTypes { block")
    text = text[: m.start()] + SIGNING + text[m.start():]

    text, n = re.subn(r"signingConfig\s*=?\s*signingConfigs\.debug",
                      "signingConfig = signingConfigs.release", text)
    if n < 1:
        sys.exit("Could not switch the release build to the release signing config")
    GRADLE.write_text(text, encoding="utf-8")
    print("Release signing configured")


if __name__ == "__main__":
    patch_manifest()
    patch_signing()
