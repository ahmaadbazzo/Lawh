#!/usr/bin/env python3
"""
Post-processes the android/ folder generated by flutter create:
  * sets the launcher label to «لَوح»
  * wires release signing for either Groovy or Kotlin Gradle DSL.
Run from the project root.
"""
import re
import sys
from pathlib import Path

ANDROID = Path("android")
MANIFEST = ANDROID / "app" / "src" / "main" / "AndroidManifest.xml"
GROOVY_GRADLE = ANDROID / "app" / "build.gradle"
KOTLIN_GRADLE = ANDROID / "app" / "build.gradle.kts"
KEYPROPS = ANDROID / "key.properties"
LABEL = "لَوح"

GROOVY_PROPS = """def keystoreProperties = new Properties()
def keystorePropertiesFile = rootProject.file('key.properties')
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(new FileInputStream(keystorePropertiesFile))
}

"""
GROOVY_SIGNING = """    signingConfigs {
        release {
            keyAlias keystoreProperties['keyAlias']
            keyPassword keystoreProperties['keyPassword']
            storeFile keystoreProperties['storeFile'] ? file(keystoreProperties['storeFile']) : null
            storePassword keystoreProperties['storePassword']
        }
    }

"""

KOTLIN_PROPS = """val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

"""
KOTLIN_SIGNING = """    signingConfigs {
        create("release") {
            keyAlias = keystoreProperties["keyAlias"] as String
            keyPassword = keystoreProperties["keyPassword"] as String
            storeFile = file(keystoreProperties["storeFile"] as String)
            storePassword = keystoreProperties["storePassword"] as String
        }
    }

"""

def patch_manifest():
    if not MANIFEST.exists():
        sys.exit("AndroidManifest.xml not found")
    text = MANIFEST.read_text(encoding="utf-8")
    new, n = re.subn(r'android:label="[^"]*"', f'android:label="{LABEL}"', text, count=1)
    if n != 1:
        sys.exit("Could not set android:label in AndroidManifest.xml")
    MANIFEST.write_text(new, encoding="utf-8")
    print("Manifest label set")

def insert_before(pattern, insertion, text, error):
    match = re.search(pattern, text, flags=re.M)
    if not match:
        sys.exit(error)
    return text[:match.start()] + insertion + text[match.start():]

def patch_groovy():
    text = GROOVY_GRADLE.read_text(encoding="utf-8")
    if "keystoreProperties" in text:
        print("Groovy release signing already configured")
        return
    text = insert_before(r"^android\s*\{", GROOVY_PROPS, text, "Could not find android { block")
    text = insert_before(r"^\s*buildTypes\s*\{", GROOVY_SIGNING, text, "Could not find buildTypes { block")
    text, n = re.subn(r"signingConfig\s*=?\s*signingConfigs\.debug",
                      "signingConfig signingConfigs.release", text)
    if n < 1:
        sys.exit("Could not switch Groovy release build to release signing")
    GROOVY_GRADLE.write_text(text, encoding="utf-8")
    print("Groovy release signing configured")

def patch_kotlin():
    text = KOTLIN_GRADLE.read_text(encoding="utf-8")
    if "keystoreProperties" in text:
        print("Kotlin release signing already configured")
        return
    text = "import java.util.Properties\n\n" + text
    text = insert_before(r"^android\s*\{", KOTLIN_PROPS, text, "Could not find android { block in build.gradle.kts")
    text = insert_before(r"^\s*buildTypes\s*\{", KOTLIN_SIGNING, text, "Could not find buildTypes { block in build.gradle.kts")
    patterns = [
        (r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)',
         'signingConfig = signingConfigs.getByName("release")'),
        (r"signingConfig\s*=\s*signingConfigs\.debug",
         'signingConfig = signingConfigs.getByName("release")'),
    ]
    total = 0
    for pattern, replacement in patterns:
        text, n = re.subn(pattern, replacement, text)
        total += n
    if total < 1:
        sys.exit("Could not switch Kotlin release build to release signing")
    KOTLIN_GRADLE.write_text(text, encoding="utf-8")
    print("Kotlin release signing configured")

def patch_signing():
    if not KEYPROPS.exists():
        print("No key.properties -> release will be debug-signed (fine for testing, NOT for the store)")
        return
    if GROOVY_GRADLE.exists():
        patch_groovy()
    elif KOTLIN_GRADLE.exists():
        patch_kotlin()
    else:
        sys.exit("Neither android/app/build.gradle nor build.gradle.kts was found")

if __name__ == "__main__":
    patch_manifest()
    patch_signing()
